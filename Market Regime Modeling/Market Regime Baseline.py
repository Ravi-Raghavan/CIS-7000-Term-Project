# 3. BASELINE MODELS (ALL BACKBONES)
# ==========================================

class FFNNClassifier(nn.Module):
    def __init__(self, input_size, sequence_length, hidden_size=64, num_classes=2):
        super().__init__()
        self.fc1 = nn.Linear(input_size * sequence_length, hidden_size)
        self.relu = nn.ReLU()
        self.fc2 = nn.Linear(hidden_size, num_classes)
        
    def forward(self, x):
        x = x.view(x.size(0), -1)
        out = self.relu(self.fc1(x))
        return self.fc2(out)

class RNNClassifier(nn.Module):
    def __init__(self, input_size, hidden_size=64, num_layers=2, num_classes=2):
        super().__init__()
        self.rnn = nn.RNN(input_size, hidden_size, num_layers, batch_first=True, dropout=0.2)
        self.fc = nn.Linear(hidden_size, num_classes)
        
    def forward(self, x):
        out, _ = self.rnn(x)
        return self.fc(out[:, -1, :])

class LSTMClassifier(nn.Module):
    def __init__(self, input_size, hidden_size=64, num_layers=2, num_classes=2):
        super().__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers, batch_first=True, dropout=0.2)
        self.fc = nn.Linear(hidden_size, num_classes)
        
    def forward(self, x):
        out, _ = self.lstm(x)
        return self.fc(out[:, -1, :])

class TCNClassifier(nn.Module):
    def __init__(self, input_size, hidden_size=64, num_classes=2):
        super().__init__()
        self.conv = nn.Conv1d(in_channels=input_size, out_channels=hidden_size, kernel_size=3, padding=1)
        self.relu = nn.ReLU()
        self.fc = nn.Linear(hidden_size, num_classes)
        
    def forward(self, x):
        x = x.transpose(1, 2)
        out = self.relu(self.conv(x))
        out, _ = torch.max(out, dim=2)
        return self.fc(out)

class TransformerClassifier(nn.Module):
    def __init__(self, input_size, hidden_size=64, num_classes=2):
        super().__init__()
        self.embedding = nn.Linear(input_size, hidden_size)
        encoder_layer = nn.TransformerEncoderLayer(d_model=hidden_size, nhead=4, batch_first=True)
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=1)
        self.fc = nn.Linear(hidden_size, num_classes)
        
    def forward(self, x):
        x = self.embedding(x)
        out = self.transformer(x)
        out = out.mean(dim=1)
        return self.fc(out)

