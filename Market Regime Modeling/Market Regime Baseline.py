# 4. EVALUATION & TRAINING LOOP
# ==========================================

def evaluate_accuracy(model, X, y):
    model.eval()
    with torch.no_grad():
        X_tensor = torch.tensor(X, dtype=torch.float32)
        y_tensor = torch.tensor(y, dtype=torch.long)
        outputs = model(X_tensor)
        _, predicted = torch.max(outputs.data, 1)
        correct = (predicted == y_tensor).sum().item()
        accuracy = 100 * correct / len(y)
    return accuracy

def run_regime_pipeline():
    df = load_and_prepare_compound_data()
    
    # Feed all the new OHLCV-derived features into the neural network backbones
    features = ['SPY_Return', 'QQQ_Return', 'SPY_Log_Return', 'QQQ_Log_Return', 
                'SPY_Volume_Ratio', 'SPY_Intraday_Vol', 'QQQ_Intraday_Vol']
    scaler = StandardScaler()
    df[features] = scaler.fit_transform(df[features])
    
    seq_length = 30
    batch_size = 64
    epochs = 10
    
    train_data, val_data, test_data = create_sequences_and_split(df, features, 'Target_Regime', seq_length)
    X_train, y_train, _ = train_data
    X_val, y_val, _ = val_data
    X_test, y_test, _ = test_data
    
    print(f"Data Split -> Train: {len(X_train)} | Val: {len(X_val)} | Test: {len(X_test)}")
    
    train_loader = DataLoader(TimeSeriesDataset(X_train, y_train), batch_size=batch_size, shuffle=True)
    
    models = {
        "FFNN/LR": FFNNClassifier(input_size=len(features), sequence_length=seq_length),
        "RNN": RNNClassifier(input_size=len(features)),
        "LSTM": LSTMClassifier(input_size=len(features)),
        "TCN": TCNClassifier(input_size=len(features)),
        "Transformer": TransformerClassifier(input_size=len(features))
    }
    
    results = []
    criterion = nn.CrossEntropyLoss()
    
    print("\n" + "="*60)
    print("--- Starting Backbone Comparison (Compound Regimes) ---")
    print("="*60)
    
    for name, model in models.items():
        print(f"Training {name} Backbone...")
        optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
        
        for epoch in range(epochs):
            model.train()
            for X_batch, y_batch in train_loader:
                optimizer.zero_grad()
                y_pred = model(X_batch)
                loss = criterion(y_pred, y_batch)
                loss.backward()
                optimizer.step()
                
        train_acc = evaluate_accuracy(model, X_train, y_train)
        val_acc = evaluate_accuracy(model, X_val, y_val)
        test_acc = evaluate_accuracy(model, X_test, y_test)
        
        results.append((name, train_acc, val_acc, test_acc))
        print(f"-> {name} | Train Acc: {train_acc:.1f}% | Val Acc: {val_acc:.1f}% | Test Acc: {test_acc:.1f}%\n")

    print("="*60)
    print(f"{'Backbone':<15} | {'Val Acc (2018-19)':<17} | {'Test Acc (2020+)':<15}")
    print("-" * 60)
    for name, train, val, test in sorted(results, key=lambda x: x[2], reverse=True):
        print(f"{name:<15} | {val:>15.2f}% | {test:>14.2f}%")
    print("="*60)

if __name__ == "__main__":
    run_regime_pipeline()